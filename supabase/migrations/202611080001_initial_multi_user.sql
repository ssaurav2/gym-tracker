-- Incline: initial multi-user schema for Supabase Postgres.
-- REVIEW FILE ONLY: Codex has not executed this migration.
--
-- HOW TO USE LATER
-- Read the entire file, then run the whole file in the Supabase SQL editor using
-- its administrative postgres role. It targets a Supabase project whose public
-- schema does not already contain exercises/sets or the Incline backend role.
-- This is a one-time migration, NOT a script to rerun after editing parts of it.
-- If objects already exist, it stops rather than dropping/replacing them.
--
-- This creates EMPTY tables. It does not read SQLite, import data, create users,
-- set passwords, configure hosting, or touch progress photos/storage.
-- The separate, reviewed import will assign existing rows to your chosen account
-- and reset the generated ID counters after preserving the old numeric IDs.
--
-- Vocabulary:
--   Constraint: a database rule rejecting invalid data.
--   Foreign key: a rule requiring a linked record to exist.
--   Role: a database permission identity (different from an app account).
--   RLS: Row Level Security, restricting which records a role can access.
--
-- Official references:
-- https://supabase.com/docs/guides/database/postgres/row-level-security
-- https://supabase.com/docs/guides/database/postgres/column-level-security
-- https://www.postgresql.org/docs/current/sql-createrole.html
-- https://www.postgresql.org/docs/current/ddl-constraints.html

-- 1. Apply all changes together. An error aborts the transaction, so no partial
-- schema is committed. If the editor leaves an aborted transaction open, use
-- its rollback/reconnect action before retrying a corrected script.
BEGIN;

-- 2. Check assumptions before changing anything. Supabase already supplies
-- auth.users and auth.uid(); this script never modifies those managed objects.
DO $preflight$
BEGIN
    IF to_regclass('auth.users') IS NULL
       OR to_regprocedure('auth.uid()') IS NULL THEN
        RAISE EXCEPTION 'Run this migration in a Supabase database with Auth available.';
    END IF;

    IF to_regclass('public.exercises') IS NOT NULL
       OR to_regclass('public.sets') IS NOT NULL
       OR to_regclass('public.exercises_id_seq') IS NOT NULL
       OR to_regclass('public.sets_id_seq') IS NOT NULL THEN
        RAISE EXCEPTION 'Incline table/sequence names already exist. Stop and review; nothing will be replaced.';
    END IF;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'incline_api') THEN
        RAISE EXCEPTION 'The incline_api role already exists. Review it before proceeding.';
    END IF;
END;
$preflight$;

-- 3. A restricted role for the future FastAPI database connection.
-- It cannot administer the database or bypass RLS, and will not own the tables.
-- NOLOGIN deliberately keeps it unusable as a login until credentials are set up
-- securely in a later step. No password or secret is stored in this file.
-- Later, an administrator can enable its login and set a generated password
-- through a secure credential setup; keep that connection URL backend-only.
-- Do not give this role to anon, authenticated, or authenticator, and never use
-- postgres/service_role credentials for ordinary FastAPI user requests.
CREATE ROLE incline_api
    NOLOGIN
    NOSUPERUSER
    NOCREATEDB
    NOCREATEROLE
    NOINHERIT
    NOREPLICATION
    NOBYPASSRLS;

-- 4. Each exercise belongs to one Supabase account.
-- GENERATED BY DEFAULT supplies IDs normally, while allowing the later admin
-- import to preserve existing IDs. The runtime role is not allowed to insert IDs.
-- RESTRICT means account deletion requires a deliberate future cleanup flow;
-- deleting an account will not silently erase lifting history through a cascade.
CREATE TABLE public.exercises (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL DEFAULT auth.uid(),
    name text NOT NULL,

    CONSTRAINT exercises_id_positive CHECK (id > 0),
    CONSTRAINT exercises_owner_fk
        FOREIGN KEY (user_id) REFERENCES auth.users (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT exercises_name_valid
        CHECK (name = btrim(name) AND name !~ '^[[:space:]]*$'),

    -- Required as the target of the two-column ownership link on sets below.
    CONSTRAINT exercises_owner_id_unique UNIQUE (user_id, id)
);

-- Names must be unique within ONE account, ignoring letter case.
-- Different users can both have "Bench Press". The API should trim before saving.
-- Postgres lower() follows the database's collation; it is not identical to Python
-- casefold() for every Unicode name. The import must report collisions for review
-- rather than silently merging/deleting exercises.
CREATE UNIQUE INDEX exercises_owner_name_unique
    ON public.exercises (user_id, lower(name));

-- 5. Each set belongs to one account AND an exercise owned by that same account.
-- No workouts/sessions, notes, bodyweight fields, or photo data are introduced.
CREATE TABLE public.sets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL DEFAULT auth.uid(),
    exercise_id bigint NOT NULL,
    weight numeric NOT NULL,
    reps integer NOT NULL,
    date date NOT NULL,

    CONSTRAINT sets_id_positive CHECK (id > 0),
    CONSTRAINT sets_owner_fk
        FOREIGN KEY (user_id) REFERENCES auth.users (id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT sets_owned_exercise_fk
        FOREIGN KEY (user_id, exercise_id)
        REFERENCES public.exercises (user_id, id)
        ON UPDATE RESTRICT ON DELETE RESTRICT,
    CONSTRAINT sets_weight_positive_finite
        CHECK (
            weight > 0
            AND weight NOT IN ('NaN'::numeric, 'Infinity'::numeric, '-Infinity'::numeric)
        ),
    CONSTRAINT sets_reps_positive CHECK (reps > 0)
);

-- Date has no CURRENT_DATE default: that would silently use the database's
-- timezone. FastAPI must supply the logging date using the agreed timezone rule.
-- The later import supplies the original dates unchanged. Integer reps disallow
-- stored fractions; FastAPI must also reject fractional inputs before SQL, since
-- Postgres can round some casts to integer. Keep the existing strict API checks.

-- 6. Indexes speed up owner filtering, History, and "Last time" queries.
-- The exercises (user_id, id) unique constraint already indexes owner-based reads.
-- Highest ID remains the latest INSERT, without warm-up filtering or smart logic.
CREATE INDEX sets_owner_newest_idx
    ON public.sets (user_id, id DESC);
CREATE INDEX sets_owner_exercise_newest_idx
    ON public.sets (user_id, exercise_id, id DESC);

-- 7. Turn RLS on before granting application access. FORCE also subjects normal
-- table-owner queries to RLS; superusers/BYPASSRLS administrators still bypass it.
-- SQL editor admin results therefore do NOT prove that app-user isolation works.
ALTER TABLE public.exercises ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exercises FORCE ROW LEVEL SECURITY;
ALTER TABLE public.sets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sets FORCE ROW LEVEL SECURITY;

-- 8. Owner-only rules for all four operations on both tables.
-- auth.uid() returns the request's Supabase account ID, or NULL without one.
-- A missing identity cannot match any required user_id, so access fails closed.
-- For direct Postgres access FastAPI MUST verify the login token first and set
-- request.jwt.claims transaction-locally with its verified "sub" account ID.
-- RLS does not verify a raw token itself. Claims and ALL queries must be in the
-- SAME explicit transaction; commit/rollback clears the request-local identity.
-- Never set user identity at connection/session scope with the transaction pooler.
--
-- These policies apply to the backend role only. Browser database roles are not
-- granted access: React uses FastAPI for lifting data, and Supabase for login.
CREATE POLICY exercises_select_own
    ON public.exercises FOR SELECT TO incline_api
    USING (user_id = (SELECT auth.uid()));
CREATE POLICY exercises_insert_own
    ON public.exercises FOR INSERT TO incline_api
    WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY exercises_update_own
    ON public.exercises FOR UPDATE TO incline_api
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY exercises_delete_own
    ON public.exercises FOR DELETE TO incline_api
    USING (user_id = (SELECT auth.uid()));

CREATE POLICY sets_select_own
    ON public.sets FOR SELECT TO incline_api
    USING (user_id = (SELECT auth.uid()));
CREATE POLICY sets_insert_own
    ON public.sets FOR INSERT TO incline_api
    WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY sets_update_own
    ON public.sets FOR UPDATE TO incline_api
    USING (user_id = (SELECT auth.uid()))
    WITH CHECK (user_id = (SELECT auth.uid()));
CREATE POLICY sets_delete_own
    ON public.sets FOR DELETE TO incline_api
    USING (user_id = (SELECT auth.uid()));

-- 9. Remove broad permissions that Supabase's default privileges may assign to
-- new tables/sequences. Only these NEW objects are affected, not other apps.
-- PUBLIC here means the built-in group of all database roles, not the schema.
REVOKE ALL PRIVILEGES ON TABLE public.exercises, public.sets
    FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL PRIVILEGES ON SEQUENCE public.exercises_id_seq, public.sets_id_seq
    FROM PUBLIC, anon, authenticated, service_role;

-- The backend can use the app schema and Supabase's identity helper, but it gets
-- no general access to auth.users, passwords, or Supabase account-management tables.
GRANT USAGE ON SCHEMA public, auth TO incline_api;
GRANT EXECUTE ON FUNCTION auth.uid() TO incline_api;

-- RLS determines WHICH rows; these grants determine WHICH operations/columns.
GRANT SELECT, DELETE ON TABLE public.exercises, public.sets TO incline_api;
GRANT INSERT (user_id, name) ON TABLE public.exercises TO incline_api;
GRANT INSERT (user_id, exercise_id, weight, reps, date)
    ON TABLE public.sets TO incline_api;
GRANT UPDATE (name) ON TABLE public.exercises TO incline_api;
GRANT UPDATE (weight, reps) ON TABLE public.sets TO incline_api;

-- No UPDATE grant on IDs, ownership, exercise links, or dates. No TRUNCATE or
-- schema-creation permissions. Sequence USAGE allows nextval() for generated IDs,
-- but does not permit setval() to reset counters; the admin import handles that.
GRANT USAGE ON SEQUENCE public.exercises_id_seq, public.sets_id_seq TO incline_api;

COMMIT;

